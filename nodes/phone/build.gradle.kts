// ---- test-rig prefill ---------------------------------------------------------
// Reinstalling a debug APK and re-typing a 48-char token and a 64-char realm key
// on a touchscreen for every build is the kind of friction that stops a thing
// from being tested at all. So the four settings can be baked into the APK as
// DEFAULTS — but they are read from nodes/local.properties, which is gitignored
// (.gitignore:119), and never from tracked source.
//
// This is the same reason mythos/.env holds the server's secrets: the repo is
// open-source and anyone who clones it supplies their own keys. Absent the file,
// or absent the keys in it, every field below is "" and the app behaves exactly
// as it does today — first launch opens Settings with nothing filled in.
//
// These land in the APK as plain constants. Anyone holding the APK can read them
// with `strings`, so this is a convenience for a LAN test rig and NOT a way to
// distribute a build. Release builds intentionally get nothing (see below).
val prefill = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun prefilled(key: String): String = (prefill.getProperty(key) ?: "").trim()

android {
    namespace = "com.mythos.nodes.phone"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.mythos.nodes.phone"
        // 29 keeps older spare handsets usable as kitchen/hallway nodes — the
        // whole point of this app is repurposing phones you already own. The BLE
        // scan permissions differ below 31, handled in ScannerService.
        minSdk = 29
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"

        // The baseline for EVERY build type: nothing prefilled. Only debug
        // overrides these, so a release APK can never carry the operator's token
        // even if local.properties is sitting right there during the build.
        buildConfigField("String", "PREFILL_SERVER_URL", "\"\"")
        buildConfigField("String", "PREFILL_AUTH_TOKEN", "\"\"")
        buildConfigField("String", "PREFILL_NODE_ID", "\"\"")
        buildConfigField("String", "PREFILL_REALM_KEY", "\"\"")
        buildConfigField("String", "PREFILL_BEACON_NAME", "\"\"")
    }

    buildTypes {
        release {
            isMinifyEnabled = false
        }
        debug {
            // Values are escaped through kotlin's own quoting: a token with a
            // stray quote would otherwise produce a BuildConfig that fails to
            // compile, which is at least loud.
            buildConfigField("String", "PREFILL_SERVER_URL", "\"${prefilled("mythos.serverUrl")}\"")
            buildConfigField("String", "PREFILL_AUTH_TOKEN", "\"${prefilled("mythos.authToken")}\"")
            buildConfigField("String", "PREFILL_NODE_ID", "\"${prefilled("mythos.nodeId")}\"")
            buildConfigField("String", "PREFILL_REALM_KEY", "\"${prefilled("mythos.realmKey")}\"")
            buildConfigField("String", "PREFILL_BEACON_NAME", "\"${prefilled("mythos.beaconName")}\"")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
        // Required from AGP 8: BuildConfig is no longer generated by default, so
        // the prefill constants above would silently not exist.
        buildConfig = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

