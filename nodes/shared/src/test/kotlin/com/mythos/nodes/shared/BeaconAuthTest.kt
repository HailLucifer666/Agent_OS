package com.mythos.nodes.shared

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

/**
 * Byte-exact conformance for the §11.2 authenticated beacon payload.
 *
 * WHY FIXTURE VECTORS AND NOT ROUND-TRIPPING. A build/verify pair that only
 * checks itself agrees with itself is worthless here: the receiver is
 * `aether-bridge/beacon_auth.py`, a different language on a different machine,
 * and the failure mode of any disagreement is a beacon that is simply never
 * seen — no error, no log, just a watch that never wins an election. A wrong
 * endianness or an off-by-one MAC truncation reads exactly like "Bluetooth is
 * flaky". So the expected bytes below were GENERATED BY beacon_auth.py itself,
 * not by this code:
 *
 *     key = bytes(range(1, 33)); uh = uid_hash_from_name("mythos-wrist")
 *     build_beacon_payload(key, uh, counter).hex()
 *
 * If a case here ever fails, the port has drifted from the receiver — fix the
 * port, never the vector, unless the Python side changed first.
 *
 * (Same lesson as BUG-175 in the main repo, where an openWakeWord port copied
 * every tensor shape correctly and missed one scaling step, leaving the
 * detector deaf at 1e-5 while looking perfectly plausible. Shapes agreeing is
 * not values agreeing.)
 */
class BeaconAuthTest {

    private val key: ByteArray = ByteArray(32) { (it + 1).toByte() }
    private val beaconName = "mythos-wrist"

    private fun ByteArray.hex(): String = joinToString("") { "%02x".format(it) }

    @Test
    fun `uid hash matches the reference implementation`() {
        // sha256("mythos-wrist")[:4] read big-endian.
        assertEquals(2961343301L, BeaconAuth.uidHashFromName(beaconName))
    }

    @Test
    fun `payload bytes match beacon_auth dot py vectors exactly`() {
        val uidHash = BeaconAuth.uidHashFromName(beaconName)
        val expected = mapOf(
            0L to "ae7401b0828345000000009cd2c3715883e2e7",
            1L to "ae7401b082834500000001199724940003430b",
            42L to "ae7401b08283450000002ac8c5e9b2ff919769",
            // The 32-bit counter's ceiling — proves the unsigned widening to
            // Long does not sign-extend on the wire.
            4294967295L to "ae7401b0828345ffffffff304741ec95dacd2a",
        )
        for ((counter, hex) in expected) {
            val payload = BeaconAuth.buildBeaconPayload(key, uidHash, counter)
            assertEquals(BeaconAuth.PAYLOAD_LENGTH, payload.size, "wrong length for counter=$counter")
            assertEquals(hex, payload.hex(), "payload mismatch for counter=$counter")
        }
    }

    @Test
    fun `magic and version occupy the first three bytes`() {
        val p = BeaconAuth.buildBeaconPayload(key, BeaconAuth.uidHashFromName(beaconName), 7L)
        assertEquals(0xAE.toByte(), p[0])
        assertEquals(0x74.toByte(), p[1])
        assertEquals(BeaconAuth.CURRENT_VERSION.toByte(), p[2])
    }

    @Test
    fun `a valid payload verifies`() {
        val uidHash = BeaconAuth.uidHashFromName(beaconName)
        val result = BeaconAuth.verifyBeacon(BeaconAuth.buildBeaconPayload(key, uidHash, 10L), key, lastCounter = 9L)
        assertTrue(result.ok, "expected ok, got ${result.reason}")
        assertEquals(uidHash, result.uidHash)
        assertEquals(10L, result.counter)
    }

    @Test
    fun `every rejection rule fires with its documented reason`() {
        val uidHash = BeaconAuth.uidHashFromName(beaconName)
        val good = BeaconAuth.buildBeaconPayload(key, uidHash, 10L)

        assertEquals("bad_length", BeaconAuth.verifyBeacon(good.copyOf(18), key, 0L).reason)

        val badMagic = good.copyOf().also { it[0] = 0x00 }
        assertEquals("bad_magic", BeaconAuth.verifyBeacon(badMagic, key, 0L).reason)

        val badVersion = good.copyOf().also { it[2] = 9 }
        assertEquals("bad_version", BeaconAuth.verifyBeacon(badVersion, key, 0L).reason)

        // §11.2: counters are strictly increasing — EQUAL is a replay too, not
        // just lower. Persisting the counter across restarts is what makes this
        // meaningful (BeaconCounterStore), so an equal-counter acceptance would
        // quietly reopen the replay window it exists to close.
        assertEquals("replay", BeaconAuth.verifyBeacon(good, key, 10L).reason)
        assertEquals("replay", BeaconAuth.verifyBeacon(good, key, 11L).reason)

        val wrongKey = ByteArray(32) { 0x7F }
        assertEquals("hmac_mismatch", BeaconAuth.verifyBeacon(good, wrongKey, 0L).reason)

        val tamperedMac = good.copyOf().also { it[18] = (it[18] + 1).toByte() }
        assertEquals("hmac_mismatch", BeaconAuth.verifyBeacon(tamperedMac, key, 0L).reason)
    }

    @Test
    fun `rotation grace window accepts a payload signed with a previous key`() {
        val uidHash = BeaconAuth.uidHashFromName(beaconName)
        val oldKey = ByteArray(32) { 0x11 }
        val newKey = ByteArray(32) { 0x22 }
        val signedWithOld = BeaconAuth.buildBeaconPayload(oldKey, uidHash, 5L)

        // Current key first, history after — a beacon that has not yet picked up
        // a rotation must not vanish mid-flight.
        assertTrue(BeaconAuth.verifyBeaconAnyKey(signedWithOld, listOf(newKey, oldKey), 0L).ok)
        assertFalse(BeaconAuth.verifyBeaconAnyKey(signedWithOld, listOf(newKey), 0L).ok)
        assertEquals(
            "no_candidate_keys",
            BeaconAuth.verifyBeaconAnyKey(signedWithOld, emptyList(), 0L).reason,
        )
    }
}
