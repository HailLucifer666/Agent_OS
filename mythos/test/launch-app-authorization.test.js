describe('every path prepares before it checks, and the click accept mints the token', () => {
  const fs = require('node:fs');
  const ROOT = path.join(__dirname, '..');
  function jsFiles(dir) {
    const out = [];
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== 'node_modules') out.push(...jsFiles(p)); } else if (e.name.endsWith('.js')) out.push(p);
    }
    return out;
  }
  // The two deliberate exemptions, each with its reason. Anything else that calls
  // leash.check() without preparing first fails here — and at runtime the leash
  // refuses an unprepared launch_app ('not-prepared'), so a miss is loud either way.
  const EXEMPT = {
    'src/core/voice/authority-gate.js': 'runApproved re-checks the SAME stored decision, which was prepared when the call was held',
    'src/core/engagements/executor.js:run_command': 'the run_command stage builds a fixed run_command decision; that tool has no prepare()',
    'server/routes/media.js': 'the media widget route builds a fixed media_key decision; that tool has no prepare()',
  };
  // Found by this sweep on its first run, 2026-09-29: server/desktop-connection.js
  // and server/test-hatch.js checked launch_app-capable decisions unprepared, and
  // were fixed; the first version also flagged a leash.check() inside a trailing
  // comment (effectors/adapter.js), hence the comment strip below.

  test('every leash.check( call site in src/, server/ and mcp/ is preceded by leash.prepare(', () => {
    const misses = [];
    for (const dir of ['src', 'server', 'mcp']) {
      for (const file of jsFiles(path.join(ROOT, dir))) {
        const rel = path.relative(ROOT, file).replace(/\\/g, '/');
        if (rel === 'src/core/leash/index.js') continue;
        const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
        lines.forEach((line, i) => {
          const code = line.replace(/\/\/.*$/, '');
          if (!/\bleash\.check\(/.test(code)) return;
          const window = lines.slice(Math.max(0, i - 2), i + 1).join('\n');
          if (/leash\.prepare\(/.test(window)) return;
          if (EXEMPT[rel]) return;
          if (rel === 'src/core/engagements/executor.js' && /run_command/.test(lines.slice(Math.max(0, i - 12), i).join('\n'))) return;
          misses.push(`${rel}:${i + 1}`);
        });
      }
    }
    assert.deepEqual(misses, [], 'these check a decision nothing prepared');
  });

  // A per-call approval is CLICK-only. The review (2026-09-29) found the spoken-yes
  // branch for it in runApproved unreachable — a proposal exists only for a call
  // the leash allowed, and the prepared record is frozen — so it was removed; the
  // re-check there is plain "allowed or not" again.
  test('the click accept mints through authority-gate.js; the spoken-yes path has no approval branch', () => {
    const server = fs.readFileSync(path.join(ROOT, 'server', 'index.js'), 'utf8');
    assert.match(server, /channel: 'confirm-accept'[^\n]*\n\s*consent: approvalConsentFor\(decision\) \}\)/);
    const gate = fs.readFileSync(path.join(ROOT, 'src', 'core', 'voice', 'authority-gate.js'), 'utf8');
    const run = gate.slice(gate.indexOf('function runApproved('), gate.indexOf('function onTurnComplete('));
    assert.match(run, /if \(!verdict \|\| !verdict\.allow\)/);
    assert.doesNotMatch(run, /approvalConsentFor|perCallApproval|APPROVAL_REASON/);
  });
});

