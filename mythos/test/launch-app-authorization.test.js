      assert.equal(w.launches()[0].target.executable, 'C:\\WINDOWS\\system32\\WindowsPowerShell\\v1.0\\PowerShell.exe',
        'the approved record launches, not a fresh lookup');
      assert.equal(w.calls.filter((c) => c.cmd === 'resolve_app').length, 1, 'exactly one resolution per decision');
