function world(configOverrides, opts) {
  const calls = [];
  const pcChild = {
    getStatus: () => ({ state: 'ONLINE' }),
    sendCommand: async (c) => {
      calls.push(c);
      if (c.cmd === 'resolve_app') return (opts && opts.hang) ? new Promise(() => {}) : { ok: true, result: RECORDS[String(c.name).toLowerCase()] || RECORDS.ghost };
      if (c.cmd === 'launch_app') return { ok: true, result: { pid: 4242, launched: true, matchedBy: 'process', resolvedName: c.name } };
      if (c.cmd === 'open_uri') return { ok: true, result: { name: c.uri, launched: true } };
      return { ok: true, result: {} };
    },
  };
  const original = Module.prototype.require;
  Module.prototype.require = function (id) { return id === '../../../adapters/pc-child' ? pcChild : original.apply(this, arguments); };
  delete require.cache[FROM_PC_PATH];
  let fromPc;
  try { fromPc = require(FROM_PC_PATH); } finally { Module.prototype.require = original; }
  const effector = effectorFromTool(fromPc.TOOLS.find((t) => t.name === 'launch_app'));
  const grantedGoal = { id: 'g1', grants: { 3: ['launch_app'] } };
  const leash = createLeash({
    bus: { emit() {}, subscribe() { return () => {}; } },
    config: Object.assign({ AUTONOMOUS_MAX_TIER: 2, MYTHOS_DRY_RUN: false, LEASH_CONFIRM_TTL_MS: 30000, CHECKPOINT_TTL_MS: 1800000,
      TRUSTED_TOOLS: '', TRUSTED_TOOLS_DISABLED: false }, configOverrides),
    identity: { checkBoundary: () => null, getMaxAutonomousTier: () => 4 },
    auditWriter: { write: () => ({ ok: true }) },
    goals: { get: (id) => (id === 'g1' ? grantedGoal : null) },
    effectors: { get: (name) => (name === 'launch_app' ? effector : undefined) },
  });
  const hub = { invoke: (tool, args, ctx) => effector.invoke(args, ctx) };
  const dispatch = (decision, extra) => dispatchAction(decision, Object.assign({ effectors: hub, bus: { emit() {} }, channel: 'test' }, extra));
  const launches = () => calls.filter((c) => c.cmd === 'launch_app' || c.cmd === 'open_uri');
  return { calls, launches, fromPc, leash, dispatch };
}

