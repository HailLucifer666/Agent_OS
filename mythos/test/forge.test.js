'use strict';

// Phase 3 of the Hermes orchestration change: forge.js now drives a hermes
// runner (runPlan/runBuild) instead of brain.think per file. These tests use
// a fake runner test double — the runner's own logic (plan parsing, the
// blocker taxonomy, directory polling) is covered separately in
// test/forge-runner.test.js; this file covers forge.js's state machine,
// checkpoint wiring, and persistence/recovery, which are unchanged in shape
// even though the underlying build mechanism changed.

const { describe, it, beforeEach, afterEach } = require('node:test');
const assert = require('node:assert/strict');
const { tempVaultDir, cleanupVaultDir, fakeBus } = require('./helpers');
const { createFsStore } = require('../src/core/memory/fs-store');
const { createForge } = require('../src/core/effectors/forge');
const validate = require('../src/core/effectors/forge-validate');

// ---- test doubles ----

function fakeCheckpoints() {
  const created = [];
  return {
    create(opts) {
      const rec = Object.assign({ id: 'cp-' + (created.length + 1) }, opts);
      created.push(rec);
      return { id: rec.id, kind: rec.kind, projectId: rec.projectId };
    },
    _created: created,
    _byKind(kind) { return created.filter((c) => c.kind === kind); },
    _last() { return created[created.length - 1]; },
    async _approve(idx) { const r = created[idx != null ? idx : created.length - 1]; return r && r.onApprove ? r.onApprove(r) : null; },
    async _reject(idx, feedback) { const r = created[idx != null ? idx : created.length - 1]; return r && r.onReject ? r.onReject(r, feedback) : null; },
  };
}

const APP_MANIFEST = {
  name: 'Todo App', kind: 'app', techNotes: 'vanilla',
  files: [{ path: 'index.html', purpose: 'shell' }, { path: 'app.js', purpose: 'logic' }],
};

// A fake hermes runner: runPlan/runBuild are configurable canned responses.
// runBuild's default behavior writes every manifest file to disk (as a real
// Hermes run would) before resolving, so forge.js's markFilesFromDisk sees
// real files via vault.exists just like production.
function fakeRunner(vault, cfg) {
  cfg = cfg || {};
  const planCalls = [];
  const buildCalls = [];
  return {
    _planCalls: planCalls,
    _buildCalls: buildCalls,
    async runPlan(spec, kind) {
      planCalls.push({ spec, kind });
      if (cfg.planResult) return cfg.planResult;
      return { ok: true, manifest: cfg.manifest || APP_MANIFEST };
    },
    async runBuild(args) {
      buildCalls.push(args);
      if (cfg.buildResult) {
        return typeof cfg.buildResult === 'function' ? cfg.buildResult(args) : cfg.buildResult;
      }
      // Default: write every planned file, report progress once, succeed.
      const files = (args.manifest && args.manifest.files) || [];
      const written = [];
      for (const f of files) {
        vault.writeText(args.dirRel + '/' + f.path, '// generated by fake hermes\n');
        written.push(f.path);
      }
      if (typeof args.onProgress === 'function') args.onProgress(written.slice());
      return { ok: true, files: written, added: [] };
    },
  };
}

function waitFor(cond, ms) {
  ms = ms || 2000;
  return new Promise((resolve, reject) => {
    const start = Date.now();
    (function loop() {
      let v = false;
      try { v = cond(); } catch (_) { v = false; }
      if (v) return resolve(v);
      if (Date.now() - start > ms) return reject(new Error('waitFor timeout'));
      setTimeout(loop, 5);
    })();
  });
}

describe('forge — multi-file build pipeline (Hermes-driven)', () => {
  let dir, bus, fs, cps;
  beforeEach(() => { dir = tempVaultDir(); bus = fakeBus(); fs = createFsStore(() => dir, bus); cps = fakeCheckpoints(); });
  afterEach(() => cleanupVaultDir(dir));

  function make(runnerCfg) {
    const runner = fakeRunner(fs, runnerCfg);
    return { forge: createForge({ config: {}, runner, bus, vault: fs, checkpoints: cps }), runner };
  }

  it('constructor requires runner (with runPlan+runBuild), vault, bus, checkpoints', () => {
    const runner = fakeRunner(fs);
    assert.throws(() => createForge({ bus, vault: fs, checkpoints: cps }));
    assert.throws(() => createForge({ runner: {}, bus, vault: fs, checkpoints: cps }));
    assert.throws(() => createForge({ runner, vault: fs, checkpoints: cps }));
    assert.throws(() => createForge({ runner, bus, checkpoints: cps }));
    assert.throws(() => createForge({ runner, bus, vault: fs }));
  });

  it('plan approved → awaiting-plan-approval + plan checkpoint armed', async () => {
    const { forge } = make();
    const { id } = forge.createProject('a todo app', 'app');
    await waitFor(() => forge.getProject(id).status === 'awaiting-plan-approval');
    const p = forge.getProject(id);
    assert.equal(p.files.length, 2);
    assert.equal(cps._byKind('plan-approval').length, 1);
    assert.equal(p.previewUrl, '/vault/builds/projects/todo-app/index.html');
  });

  it('runPlan reason:plan-unparseable → failed, never throws', async () => {
    const { forge } = make({ planResult: { ok: false, reason: 'plan-unparseable', error: 'Hermes did not return a JSON file plan' } });
    const { id } = forge.createProject('a todo app', 'app');
    await waitFor(() => forge.getProject(id).status === 'failed');
    assert.match(forge.getProject(id).error, /JSON file plan/);
  });

  it('full happy path: create → approve plan → build → approve final → done', async () => {
    const { forge } = make();
    const { id } = forge.createProject('a todo app', 'app');
    await waitFor(() => forge.getProject(id).status === 'awaiting-plan-approval');
    await cps._approve(0); // plan-approval onApprove runs runBuildStage
    await waitFor(() => forge.getProject(id).status === 'awaiting-final-review');
    assert.ok(fs.exists('builds/projects/todo-app/index.html'));
    assert.ok(fs.exists('builds/projects/todo-app/app.js'));
    assert.equal(cps._byKind('final-review').length, 1);
    await cps._approve(); // final-review onApprove
    assert.equal(forge.getProject(id).status, 'done');
    assert.equal(forge.getProject(id).filesDone, 2);
  });

  it('plan reject → plan-rejected terminal', async () => {
    const { forge } = make();
    const { id } = forge.createProject('a todo app', 'app');
    await waitFor(() => forge.getProject(id).status === 'awaiting-plan-approval');
    await cps._reject(0);
    assert.equal(forge.getProject(id).status, 'plan-rejected');
  });

  it('runBuild cwd/dirRel is pinned to builds/projects/<slug>', async () => {
    const { forge, runner } = make();
    const { id } = forge.createProject('a todo app', 'app');
    await waitFor(() => forge.getProject(id).status === 'awaiting-plan-approval');
    await cps._approve(0);
    await waitFor(() => forge.getProject(id).status === 'awaiting-final-review');
    assert.equal(runner._buildCalls[0].dirRel, 'builds/projects/todo-app');
  });

  it("classify reason:'partial' → awaiting-mid-build-decision; approve keeps it, reject abandons", async () => {
    const { forge } = make({
      buildResult: (args) => {
        fs.writeText(args.dirRel + '/index.html', '<html></html>');
        return { ok: false, reason: 'partial', missing: ['app.js'], error: 'planned files not produced: app.js', files: ['index.html'], added: [] };
      },
    });
    const { id } = forge.createProject('a todo app', 'app');
    await waitFor(() => forge.getProject(id).status === 'awaiting-plan-approval');
    await cps._approve(0);
    await waitFor(() => forge.getProject(id).status === 'awaiting-mid-build-decision');
    assert.match(forge.getProject(id).error, /app\.js/);
    assert.equal(cps._byKind('mid-build').length, 1);
    await cps._approve(); // mid-build onApprove → keep what built
    await waitFor(() => forge.getProject(id).status === 'awaiting-final-review');
  });

  it("mid-build reject → failed, 'abandoned after partial build'", async () => {
    const { forge } = make({
      buildResult: () => ({ ok: false, reason: 'partial', missing: ['app.js'], error: 'planned files not produced: app.js', files: [], added: [] }),
    });
    const { id } = forge.createProject('a todo app', 'app');
    await waitFor(() => forge.getProject(id).status === 'awaiting-plan-approval');
    await cps._approve(0);
    await waitFor(() => forge.getProject(id).status === 'awaiting-mid-build-decision');
    await cps._reject();
    assert.equal(forge.getProject(id).status, 'failed');
    assert.match(forge.getProject(id).error, /abandoned/);
  });

  for (const reason of ['timeout', 'hermes-error', 'no-output']) {
    it(`classify reason:'${reason}' → hard failure, never a partial/mid-build decision`, async () => {
      const { forge } = make({ buildResult: { ok: false, reason, error: 'blocked: ' + reason } });
      const { id } = forge.createProject('a todo app', 'app');
      await waitFor(() => forge.getProject(id).status === 'awaiting-plan-approval');
      await cps._approve(0);
      await waitFor(() => forge.getProject(id).status === 'failed');
      assert.match(forge.getProject(id).error, new RegExp(reason));
    });
  }

  it('an unplanned file Hermes added is appended as done, not treated as missing', async () => {
    const { forge } = make({
      buildResult: (args) => {
        fs.writeText(args.dirRel + '/index.html', '<html></html>');
        fs.writeText(args.dirRel + '/app.js', 'x');
        fs.writeText(args.dirRel + '/README.md', 'notes');
        return { ok: true, files: ['index.html', 'app.js', 'README.md'], added: ['README.md'] };
      },
    });
    const { id } = forge.createProject('a todo app', 'app');
    await waitFor(() => forge.getProject(id).status === 'awaiting-plan-approval');
    await cps._approve(0);
    await waitFor(() => forge.getProject(id).status === 'awaiting-final-review');
    const p = forge.getProject(id);
    const readme = p.files.find((f) => f.path === 'README.md');
    assert.ok(readme, 'unplanned file must be appended to p.files');
    assert.equal(readme.status, 'done');
  });

  it('crash recovery: seeded generating project → interrupted at init', () => {
    fs.writeJSON('Checkpoints/forge-projects.json', [
      { id: 'forge-old', name: 'X', kind: 'app', status: 'generating', spec: 's', slug: 'x', files: [{ path: 'a.js', status: 'generating', attempts: 1 }], manifest: { name: 'X', kind: 'app', files: [] }, createdAt: 1 },
    ]);
    const runner = fakeRunner(fs);
    const forge = createForge({ config: {}, runner, bus, vault: fs, checkpoints: cps });
    forge.init();
    assert.equal(forge.getProject('forge-old').status, 'interrupted');
  });

  it('awaiting-plan-approval seed → init re-arms a fresh plan checkpoint', () => {
    fs.writeJSON('Checkpoints/forge-projects.json', [
      { id: 'forge-a', name: 'A', kind: 'app', status: 'awaiting-plan-approval', spec: 's', slug: 'a',
        files: [{ path: 'index.html', purpose: 'p', status: 'pending', attempts: 0 }],
        manifest: { name: 'A', kind: 'app', techNotes: '', files: [{ path: 'index.html', purpose: 'p', status: 'pending', attempts: 0 }] }, createdAt: 1 },
    ]);
    const runner = fakeRunner(fs);
    const forge = createForge({ config: {}, runner, bus, vault: fs, checkpoints: cps });
    forge.init();
    assert.equal(cps._byKind('plan-approval').length, 1);
    assert.equal(cps._last().projectId, 'forge-a');
  });

  it('resumeProject with a manifest re-runs runBuild against the same project dir', async () => {
    fs.writeJSON('Checkpoints/forge-projects.json', [
      { id: 'forge-b', name: 'Todo App', kind: 'app', status: 'interrupted', spec: 's', slug: 'todo-app',
        files: APP_MANIFEST.files, manifest: APP_MANIFEST, createdAt: 1 },
    ]);
    const { forge, runner } = make();
    forge.init();
    const r = forge.resumeProject('forge-b');
    assert.equal(r.ok, true);
    await waitFor(() => forge.getProject('forge-b').status === 'awaiting-final-review');
    assert.equal(runner._buildCalls[0].dirRel, 'builds/projects/todo-app');
  });

  it('resumeProject with no manifest replans instead of building', async () => {
    fs.writeJSON('Checkpoints/forge-projects.json', [
      { id: 'forge-c', name: 'project', kind: 'app', status: 'interrupted', spec: 's', slug: null, files: [], manifest: null, createdAt: 1 },
    ]);
    const { forge, runner } = make();
    forge.init();
    const r = forge.resumeProject('forge-c');
    assert.equal(r.status, 'planning');
    await waitFor(() => forge.getProject('forge-c').status === 'awaiting-plan-approval');
    assert.equal(runner._planCalls.length, 1);
  });

  it('resumeProject refuses a project that is not interrupted', () => {
    const { forge } = make();
    const { id } = forge.createProject('a todo app', 'app');
    const r = forge.resumeProject(id);
    assert.equal(r.ok, false);
  });
});

describe('forge-validate — slug/URL helpers', () => {
  it('computePreviewUrl prefers index.html then any html then md', () => {
    assert.equal(validate.computePreviewUrl('s', [{ path: 'style.css' }, { path: 'index.html' }]), '/vault/builds/projects/s/index.html');
    assert.equal(validate.computePreviewUrl('s', [{ path: 'page.html' }]), '/vault/builds/projects/s/page.html');
    assert.equal(validate.computePreviewUrl('s', [{ path: 'readme.md' }]), '/vault/builds/projects/s/readme.md');
    assert.equal(validate.computePreviewUrl('s', [{ path: 'a.js' }]), null);
  });

  it('slugify + uniqueSlug', () => {
    assert.equal(validate.slugify('Todo App!!'), 'todo-app');
    assert.equal(validate.uniqueSlug('x', (s) => s === 'x'), 'x-2');
  });
});
