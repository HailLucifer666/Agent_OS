// THE FILED CAUSE IS WRONG, AND (e) BELOW PROVES IT. Measured 2026-09-16 against
// the code: live-tool-adapter's evaluateOutcome() folds unverified INTO ok
// (`ok: dispatchOk && !isUnverified`), commitAction() writes that `ok:false` to
// the recent-action ledger, and detectUnbackedClaims() reads `a.ok === true`
// for backing — so an unverified row backs nothing. The same session's
// unverified `open_web` x2 WERE caught: three `claimed-action-not-taken
// target:opening` events in 2026-09-11.jsonl. The caveat is not dropped.
//
// THE REAL GAP IS THE CATEGORY TABLE. CLAIM_CATEGORIES had no category whose
// verb is "clicked", so a false "I clicked the play button" had no shape to be
// matched against, however honest the row underneath it was. Same class as
