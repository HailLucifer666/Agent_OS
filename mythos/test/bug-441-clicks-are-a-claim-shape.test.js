//
// FIXTURE IS THE WIRE, AND (a) PROVES THE WIRE. The reviewer's probe on
// 2026-09-16: a hand-built `{ok:true, unverified:true}` row fed straight to
// the detector yields ZERO claims (ok:true backs), so a test built on that
// shape passes vacuously. (a) drives the real adapter with a real dispatch
// outcome and reads the ledger row BACK, asserting the shape the pure tests
// (b)-(f) use. Two routes, one answer.
//
// THE BOUNDS ARE THE POINT. "pressed" is deliberately NOT a clicking verb —
// a successful browser_press_key would be falsely retracted (d). The tool set
// is every `*click*` name in TIER_TABLE, derived in
// test/claim-check-categories.test.js rather than typed twice. And (f) pins an
// honest limit: the detector backs by TOOL NAME, so an earlier real click in
