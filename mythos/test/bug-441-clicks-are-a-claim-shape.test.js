//
// WHAT THE FIX CAN AND CANNOT DO, per path (operator decision D3, 2026-09-16:
// "also suppress-before"):
//   - Gemini Live: the audio is generated by Gemini and has already been heard
//     when onLiveTurnComplete runs (live-session.js: "It cannot un-speak the
//     audio"). The earliest correction is the ad4-correction-retract notice,
//     which (a) asserts. Suppression before speech is impossible by
//     construction on this path.
//   - Legacy text->TTS: the false sentence is now REPLACED by the correction
//     instead of read out and then corrected (voice-agent.js; pinned in
