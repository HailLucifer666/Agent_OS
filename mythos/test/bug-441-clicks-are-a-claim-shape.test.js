const { test, describe } = require('node:test');
const assert = require('node:assert/strict');

const { createLiveToolAdapter } = require('../src/core/voice/live-tool-adapter');
const { summarizeActionsForResult } = require('../src/core/voice/action-outcome-summary');
const { CLAIM_CATEGORIES, detectUnbackedClaims, replaceUnbackedClaims } = require('../src/core/voice/claim-check');
const { actionStatus } = require('../src/core/voice/action-evidence-ledger');

// Verbatim reason from the 2026-09-11 Audit rows (BUGS.md BUG-441).
const REAL_UNVERIFIED_REASON = 'clicked "Play" from page script because it never became visibly '
  + 'actionable — a script click skips the checks that prove a real user could have';

// The shape commitAction writes for an awaited unverified outcome — asserted
// against the adapter's own ledger in (a) before any pure test relies on it.
const UNVERIFIED_CLICK_ROW = {
  tool: 'browser_click', ok: false, unverified: true, dispatchOk: true, status: 'unverified',
};
const okRow = (tool) => ({ tool, ok: true, unverified: false, dispatchOk: true, status: 'ok' });

function harness(outcome) {
  const injected = [];
  const anomalies = [];
  const episodic = [];
  const adapter = createLiveToolAdapter({
    leash: {
      check: () => ({ allow: true, requireConfirm: false, tier: 2, reason: 'within-autonomous-max' }),
      confirm: { create: () => 'confirm-441' },
    },
    dispatchAction: async () => outcome,
    bus: { emit: (type, payload) => { if (type === 'health.anomaly') anomalies.push(payload); } },
    logger: { warn() {}, info() {} },
    connectionId: 'conn-441',
    memory: { working: { tick: 1 }, episodic: { write: (rec) => episodic.push(rec) } },
    historyAppend: () => {},
    reflection: null,
    summarizeActionsForResult,
    getLiveSession: () => ({ isOpen: () => true, sendText: (t) => injected.push(t) }),
    toolAckDeadlineMs: 500,
  });
  return { adapter, injected, anomalies, episodic };
}

function call(adapter, id, name, args) {
  const responses = [];
  return adapter
    .handleLiveToolCalls([{ id, name, args: args || {} }], { sendToolResponse: (r) => responses.push(...r) })
    .then(() => responses);
}

// REVERSED 2026-09-26 (B2b-2, BUG-448; operator decision that day): a click that was DELIVERED
// but whose effect could not be confirmed makes "I clicked" TRUE — the click happened. What it
// does not back is "it's playing"; that needs the player's evidence (B2b-3). Measured before the
// change: the 2026-09-24 20:47:41 sentence "I clicked on that spot based on the coordinates, but
// I can't confirm it actually started playing." was retracted over a delivered click_at, and the
// retraction was itself the false statement. So (a) and (a2) now pin the opposite of what they
// pinned on 2026-09-16, and (a0) keeps the retraction path covered with a click that FAILED.
describe('BUG-441 — "I clicked" is a claim; a delivered click backs it, a failed one does not', () => {
  test('(a0) a FAILED click, through the real adapter, is flagged and retracted', async () => {
    const { adapter, injected, anomalies } = harness({ ok: false, result: { error: 'no element matches button.play' } });
    await call(adapter, 'c0', 'browser_click', { selector: 'button.play' });
    adapter.onLiveTurnComplete({ userText: 'play it', assistantText: 'I clicked the play button for you.', turnId: 1 });
    const flagged = anomalies.filter((a) => a.kind === 'claimed-action-not-taken');
    assert.equal(flagged.length, 1, JSON.stringify(flagged));
    assert.equal(flagged[0].target, 'clicking');
    assert.equal(flagged[0].claimedTool, 'browser_click');
    assert.equal(flagged[0].claimedToolStatus, 'failed');
    const notice = injected.find((t) => /CORRECTION/.test(t));
    assert.ok(notice, 'the retraction notice is the earliest correction Live allows — the audio is already heard');
    assert.match(notice, /browser_click/, 'the correction must name the tool');
    assert.match(notice, /did NOT happen/);
  });

  test('(a) the real 2026-09-11 outcome, through the real adapter: the delivered click backs "I clicked"', async () => {
    const { adapter, injected, anomalies } = harness({
      ok: true, unverified: true, reason: REAL_UNVERIFIED_REASON, result: {},
    });
    await call(adapter, 'c1', 'browser_click', { selector: 'button.play' });

    // Two routes, one answer: the row the adapter really wrote is the row the
    // pure tests below are built from.
    const row = adapter._internal.liveTurnActions[0];
    assert.equal(row.tool, 'browser_click');
    assert.equal(row.ok, false, 'evaluateOutcome folds unverified into ok:false — the wire is NOT {ok:true, unverified:true}');
    assert.equal(row.unverified, true);
    // status is not stored on the turn row; the ledger and the detector call site
    // both derive it through actionStatus(), so this reads it the same way.
    assert.equal(actionStatus(row), 'unverified');

    adapter.onLiveTurnComplete({ userText: 'play it', assistantText: 'I clicked the play button for you.', turnId: 1 });

    const flagged = anomalies.filter((a) => a.kind === 'claimed-action-not-taken');
    assert.deepStrictEqual(flagged, [], 'the click was delivered: retracting "I clicked" would be the false statement');
    assert.ok(!injected.some((t) => /CORRECTION/.test(t)), 'no retraction notice');
  });

  test('(a2) "tapped" is the second owned verb: a failed tap is flagged, a delivered one is not', () => {
    const failedTap = { tool: 'browser_click', ok: false, unverified: false, dispatchOk: false, status: 'failed' };
    const claims = detectUnbackedClaims('I tapped the play button.', [failedTap], []);
    assert.equal(claims.length, 1);
    assert.equal(claims[0].category, 'clicking');
    assert.deepStrictEqual(detectUnbackedClaims('I tapped the play button.', [UNVERIFIED_CLICK_ROW], []), []);
  });

  test('(b) adjacent: a genuine ok:true browser_click backs the same sentence', () => {
    const claims = detectUnbackedClaims('I clicked the play button for you.', [okRow('browser_click')], []);
    assert.deepStrictEqual(claims, [], 'a real click must back the claim — flagging it retracts the truth (BUG-434\'s failure)');
  });

  test('(c) adjacent: a successful right_click_at backs "I clicked the button"', () => {
    const claims = detectUnbackedClaims('I clicked the button.', [okRow('right_click_at')], []);
    assert.deepStrictEqual(claims, [], 'right_click_at is a *click* tool and must be in the category');
  });

  test('(d) adjacent: "I pressed Enter" is owned by NO category, with or without a key tool', () => {
    // Deliberate non-change. "pressed" is excluded from the clicking verbs:
    // a successful browser_press_key is not a click and would be falsely
    // retracted. A keys category is out of this fix's scope.
    assert.deepStrictEqual(detectUnbackedClaims('I pressed Enter.', [okRow('browser_press_key')], []), []);
    assert.deepStrictEqual(detectUnbackedClaims('I pressed Enter.', [], []), [],
      'no category owns "pressed" — if one appears, decide its tools deliberately');
  });

  test('(e) negative control: the unverified open_web from the same session was ALREADY caught', () => {
    // This passes with the clicking category deleted. It is what disproves the
    // filed cause ("the caveat is dropped"): the mechanism works, the table
    // had a hole.
    const row = { tool: 'open_web', ok: false, unverified: true, dispatchOk: true, status: 'unverified' };
    const claims = detectUnbackedClaims('I opened it for you.', [row], []);
    assert.equal(claims.length, 1);
    assert.equal(claims[0].category, 'opening');
  });

  test('(f) known limit: an earlier real click in the window backs a later false one', () => {
    // The detector backs by TOOL NAME, not by action identity. A real
    // browser_click two turns ago makes "I clicked the pause button" backed
    // even though THIS turn's browser_click was unverified. Detecting that
    // needs the target in the sentence matched to the action's args, which no
    // category does. Pinned so the residual is a decision; recorded in BUGS.md.
    // Since B2b-2 (2026-09-26) the delivered row backs it on its own as well; the residual
    // that stands is the TARGET: clicks are not matched to what was clicked (opening is).
    const claims = detectUnbackedClaims(
      'I clicked the pause button.',
      [UNVERIFIED_CLICK_ROW],
      [okRow('browser_click')],
    );
    assert.deepStrictEqual(claims, [], 'if this starts flagging, the evidence model changed — update BUGS.md 441 too');
  });

  test('(h) legacy text: replaceUnbackedClaims removes only the sentence whose tool really failed', () => {
    // The gmail_send sentence is flagged too (voice-agent passes failed actions
    // alone, so nothing "backs" it) but no failed gmail_send exists, so it stays.
    const say = 'I sent the email. I opened the page for you.';
    const unproven = [{ tool: 'open_web', ok: false, summary: 'no browser session available' }];
    const claims = detectUnbackedClaims(say, unproven.map((a) => ({ tool: a.tool, ok: false })), [], { voiceHonesty: false });
    const out = replaceUnbackedClaims(say, claims, unproven);
    assert.equal(out, 'I sent the email. open_web did not succeed — no browser session available.');
  });

  test('(i) legacy text: an unverified action speaks its honest reason, and no clause means no change', () => {
    const say = 'I clicked the play button for you.';
    const unproven = [{ tool: 'browser_click', ok: true, unverified: true, raw: { reason: REAL_UNVERIFIED_REASON } }];
    const claims = detectUnbackedClaims(say, [{ tool: 'browser_click', ok: false }], [], { voiceHonesty: false });
    assert.equal(replaceUnbackedClaims(say, claims, unproven),
      'browser_click did not succeed — ' + REAL_UNVERIFIED_REASON + '.');
    assert.equal(replaceUnbackedClaims(say, [], unproven), say, 'no claims: the reply is returned verbatim');
    assert.equal(replaceUnbackedClaims(say, claims, []), say, 'claims but no failed action to name: untouched');
  });

  test('(g) the category exists and carries no backingTools', () => {
    const clicking = CLAIM_CATEGORIES.find((c) => c.name === 'clicking');
    assert.ok(clicking, 'clicking category must exist');
    assert.equal(clicking.backingTools, undefined,
      'no other tool makes "I clicked" true — a see_and_click IS a click tool and is owned, not backing');
  });
});

